"""Small building blocks for reStructuredText output.

All functions return lists of lines without trailing newlines; ``page`` joins
them into the final file content.
"""

import re

GENERATED_NOTE = ".. This file is generated by the converter package (python -m converter). Do not edit it manually."

_INLINE_MARKUP = re.compile(r"([\\*`|_])")
# Text such as "1. Draw", "5a. Option" or "A. Define" would otherwise become an enumerated list.
_LEADING_ENUMERATOR = re.compile(r"^(\(?[0-9A-Za-z]{1,3})([.)])(?=\s|$)")
_LEADING_BULLET = re.compile(r"^([-+•])(?=\s|$)")


def escape(text: str) -> str:
    escaped = _INLINE_MARKUP.sub(r"\\\1", text)
    escaped = _LEADING_ENUMERATOR.sub(r"\1\\\2", escaped)
    return _LEADING_BULLET.sub(r"\\\1", escaped)


def heading(text: str, underline: str) -> list[str]:
    title = escape(text)
    return [title, underline * len(title), ""]


def label(name: str) -> list[str]:
    return [f".. _{name}:", ""]


def indent(lines: list[str], spaces: int) -> list[str]:
    prefix = " " * spaces
    return [prefix + line if line else "" for line in lines]


def bullet_item(lines: list[str]) -> list[str]:
    """Format lines as one bullet list item; blank lines separate paragraphs within the item."""
    if not lines:
        return []
    return [f"* {lines[0]}", *indent(lines[1:], 2), ""]


def image(path: str, alt: str, width: str | None = None, target: str | None = None) -> list[str]:
    lines = [f".. image:: {path}", f"   :alt: {alt}"]
    if width:
        lines.append(f"   :width: {width}")
    if target:
        lines.append(f"   :target: {target}")
    return lines


def list_table(header: list[str], rows: list[list[list[str]]], widths: list[int] | None = None) -> list[str]:
    """Return a list-table; every cell is given as a list of lines, an empty list gives an empty cell."""
    lines = [".. list-table::", "   :header-rows: 1"]
    if widths:
        lines.append(f"   :widths: {' '.join(str(width) for width in widths)}")
    lines.append("")
    for row in [[[escape(cell)] for cell in header], *rows]:
        for column, cell in enumerate(row):
            marker = "* -" if column == 0 else "  -"
            if not cell:
                lines.append(f"   {marker}")
                continue
            lines.append(f"   {marker} {cell[0]}")
            lines.extend(indent(cell[1:], 7))
    lines.append("")
    return lines


def page(lines: list[str]) -> str:
    while lines and lines[-1] == "":
        lines = lines[:-1]
    return "\n".join([GENERATED_NOTE, "", *lines]) + "\n"
